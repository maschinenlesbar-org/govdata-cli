export const NOT_FOUND = {"help":"https://ckan.govdata.de/api/3/action/help_show?name=package_show","error":{"__type":"Not Found Error","message":"Nicht gefunden"},"success":false};

/** Datasets of a recorded search, as `JsonObject`s. */
type Dataset = (typeof SEARCH_TRINKWASSERBRUNNEN.results)[number] | (typeof SEARCH_FAHRRADZAEHLSTELLEN.results)[number];

/** A CKAN success envelope. */
const ok = (result: unknown): HttpResponse => jsonResponse({ help: "https://ckan.govdata.de/api/3/action/help_show?name=package_search", success: true, result });

/** The spellings of a format in a `res_format:("A" OR "B")` filter, or undefined for another filter. */
function formatsIn(filter: string): string[] | undefined {
  const match = /^res_format:\((.*)\)$/.exec(filter);
  if (match === null) return undefined;
  return [...(match[1] as string).matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => (m[1] as string).replace(/\\(.)/g, "$1"));
}

/** Whether a recorded dataset passes one filter (those the operations send). */
function passes(dataset: Dataset, filter: string): boolean {
  const formats = formatsIn(filter);
  if (formats !== undefined) return dataset.resources.some((r) => formats.includes(r.format));
  if (filter === "num_resources:[1 TO *]") return dataset.num_resources >= 1;
  const organization = /^organization:"(.*)"$/.exec(filter);
  if (organization !== null) return dataset.organization.name === organization[1];
  const theme = /^groups:(\w+)$/.exec(filter);
  if (theme !== null) return dataset.groups.some((g) => g.name === theme[1]);
  const publisher = /^extras_publisher_name:"(.*)"$/.exec(filter);
  if (publisher !== null) return dataset.extras.some((e) => e.key === "publisher_name" && e.value.includes(publisher[1] as string));
  return true;
}

/** The recorded facets for `q`: Verkehr, Radverkehr, or the whole catalogue. */
function facetsFor(q: string | null): Record<string, { title: string; items: { name: string; display_name: string; count: number }[] }> {
  if (q === "Verkehr") return { ...FACETS_VERKEHR_TOP6.search_facets, ...FACETS_VERKEHR_LICENCES.search_facets };
  if (q === "Radverkehr") return FACETS_RADVERKEHR_ALL.search_facets;
  if (q === null) return FACETS_CATALOGUE.search_facets;
  return {};
}

/** CKAN's answer to package_search, from the recorded searches and facets. */
function packageSearch(url: URL): HttpResponse {
  const q = url.searchParams.get("q");
  const fq = [...new Set(url.searchParams.getAll("fq_list"))];
  const rows = Number(url.searchParams.get("rows") ?? "10");
  const start = Number(url.searchParams.get("start") ?? "0");
  const fields = JSON.parse(url.searchParams.get("facet.field") ?? "[]") as string[];
  const limit = Number(url.searchParams.get("facet.limit") ?? "50");
  const recorded = q === "Trinkwasserbrunnen" ? SEARCH_TRINKWASSERBRUNNEN : q === "Fahrradzählstellen" ? SEARCH_FAHRRADZAEHLSTELLEN : undefined;
  let count: number;
  let results: Dataset[] = [];
  let formats: { name: string; display_name: string; count: number }[] | undefined;
  if (recorded !== undefined) {
    const matching = (recorded.results as Dataset[]).filter((d) => fq.every((f) => passes(d, f)));
    count = fq.length === 0 ? recorded.count : matching.length;
    results = matching.slice(start, start + rows);
    // The format facet of the recorded datasets that match (what the format filter reads its spellings from).
    const byFormat = new Map<string, number>();
    for (const d of matching) for (const format of new Set(d.resources.map((r) => r.format))) byFormat.set(format, (byFormat.get(format) ?? 0) + 1);
    formats = [...byFormat].map(([name, n]) => ({ name, display_name: name, count: n }));
  } else if (fq.length === 0) {
    count = q === "Verkehr" ? FACETS_VERKEHR_TOP6.count : q === "Radverkehr" ? FACETS_RADVERKEHR_ALL.count : q === null ? FACETS_CATALOGUE.count : 0;
  } else {
    count = q === null && fq.length === 1 && fq[0] === 'extras_publisher_name:"Stadt Dortmund"' ? 792 : 0;
  }
  const facets = count === 0 ? {} : formats !== undefined ? { res_format: { title: "res_format", items: formats } } : facetsFor(q);
  const searchFacets = Object.fromEntries(
    fields.map((field) => {
      const items = facets[field]?.items ?? [];
      return [field, { title: field, items: limit === -1 ? items : items.slice(0, limit) }];
    }),
  );
  return ok({ count, results, sort: "score desc, metadata_modified desc", search_facets: searchFacets });
}

/** The API's answer to `request`, from the recorded ones. */
export function govdataAnswer(request: HttpRequest): HttpResponse {
  const url = new URL(request.url);
  if (url.pathname === "/api/3/action/package_search") return packageSearch(url);
  if (url.pathname === "/api/3/action/package_show") {
    return url.searchParams.get("id") === DATASET_WUPPERTAL.name ? ok(DATASET_WUPPERTAL) : jsonResponse(NOT_FOUND, 404);
  }
  return jsonResponse({ help: "", success: false, error: { __type: "Not Found Error", message: "Not found" } }, 404);
}

